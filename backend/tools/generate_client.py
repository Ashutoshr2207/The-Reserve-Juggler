"""Generate a Python integration client from unchanged OpenAPI operation IDs."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render():
    source = (ROOT / 'contracts/openapi.json').read_bytes()
    contract = json.loads(source)
    lines = ['"""Generated by tools/generate_client.py; do not edit."""',
             'from app.api.client_runtime import ContractClient', '',
             f'CONTRACT_SHA256 = {hashlib.sha256(source).hexdigest()!r}', '', '',
             'class BackendClient(ContractClient):']
    for methods in contract['paths'].values():
        for operation in methods.values():
            op = operation['operationId']
            method = re.sub(r'(?<!^)(?=[A-Z])', '_', op).lower()
            lines.extend([f'    def {method}(self, **kwargs):',
                          f'        return self.call({op!r}, **kwargs)', ''])
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'app/api/generated_client.py'
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != render():
            raise SystemExit('Generated client is stale')
        print('Generated client matches canonical OpenAPI (12 operations).')
    else:
        target.write_text(render(), encoding='utf-8', newline='\n')
